/**
 * One rak'ah, from standing to the end of the second sajdah.
 * @param {number} rakah         which rak'ah this is (1-based)
 * @param {boolean} withSurah    read an extra surah after Fatiha (first two rak'ahs only)
 * @param {object|null} entry    the step that gets you into the standing position
 */
function buildRakah(rakah, withSurah, entry) {
  const steps = []
  if (entry) steps.push(entry)
  if (rakah === 1) steps.push(HANDS_ON_CHEST, DUA_ISTIFTAH, TAAWWUZ)
  else steps.push(TASMIYA)
  steps.push(FATIHA, rakah <= 2 ? AMEEN : AMEEN_QUIET)
  if (withSurah) steps.push(FOUR_QULS)
  steps.push(RUKU, QAWMA, SAJDA_1, JALSA, SAJDA_2)
  return steps.map((step, i) => ({ ...step, rakah, id: `r${rakah}-${i}-${step.title}` }))
}

/**
 * The full step list for one prayer's fard rak'ahs.
 * Rak'ahs 1-2 include an extra surah; a middle tashahhud appears after rak'ah 2
 * whenever the prayer is longer than two rak'ahs.
 */
export function buildNamazSteps(prayerId) {
  const prayer = getPrayer(prayerId)
  if (!prayer) return []

  const total = prayer.fard
  const steps = []

  for (let rakah = 1; rakah <= total; rakah += 1) {
    let entry = null
    if (rakah === 1) entry = TAKBIR
    else if (rakah === 3) entry = STAND_FROM_TASHAHHUD
    else entry = STAND_UP

    steps.push(...buildRakah(rakah, rakah <= 2, entry))

    const isLast = rakah === total
    if (isLast) {
      steps.push(
        { ...TASHAHHUD, rakah, id: `r${rakah}-tashahhud` },
        { ...DUROOD, rakah, id: `r${rakah}-durood` },
        { ...DUA_BEFORE_SALAM, rakah, id: `r${rakah}-dua` },
        { ...SALAM, rakah, id: `r${rakah}-salam` },
      )
    } else if (rakah === 2) {
      steps.push({
        ...TASHAHHUD,
        key: 'tashahhudMiddle',
        title: 'درمیانی تشہد',
        do: 'دوسری رکعت کے بعد بیٹھ جائیں اور صرف تشہد پڑھیں (درود اور دعا آخری رکعت میں پڑھیں گے):',
        rakah,
        id: `r${rakah}-tashahhud-middle`,
      })
    }
  }

  return steps
}
