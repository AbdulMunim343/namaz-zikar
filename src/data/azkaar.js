/** ایک وقت (صبح یا شام) کے لیے اذکار کی فہرست۔ */
export function getAzkaar(timeOfDay) {
  return AZKAAR.map((z) => ({
    id: z.id,
    name: z.name,
    times: z.times,
    virtue: z.virtue,
    audio: z.audio,
    arabic: z.arabic[timeOfDay],
    translit: z.translit[timeOfDay],
    meaning: z.meaning[timeOfDay],
  }))
}

/** شام ۴ بجے کے بعد ایپ خودبخود «شام» والا صفحہ کھولتی ہے۔ */
export function defaultTimeOfDay(now = new Date()) {
  const hour = now.getHours()
  return hour >= 16 || hour < 4 ? 'evening' : 'morning'
}
