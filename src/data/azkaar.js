      'اللہ کے سوا کوئی معبود نہیں، وہ اکیلا ہے، اُس کا کوئی شریک نہیں۔ اُسی کی بادشاہی ہے اور اُسی کی تعریف ہے، اور وہ ہر چیز پر قادر ہے۔',
